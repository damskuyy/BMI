<script>
document.addEventListener('DOMContentLoaded', function(){
  // helper easing scroll (easeOutCubic)
  function smoothScrollTo(el, to, duration){
    const start = el.scrollLeft;
    const change = to - start;
    const startTime = performance.now();
    const easeOutCubic = t => 1 - Math.pow(1 - t, 3);
    let req;
    function animate(now){
      const elapsed = now - startTime;
      const t = Math.min(1, elapsed / duration);
      el.scrollLeft = start + change * easeOutCubic(t);
      if(t < 1) req = requestAnimationFrame(animate);
    }
    req = requestAnimationFrame(animate);
    return () => cancelAnimationFrame(req);
  }

  // New helper: retrigger caption animation on a rolling-gallery element
  function animateCaptionFor(parent){
    if(!parent) return;
    const cap = parent.querySelector('.gallery-row-caption');
    if(!cap) return;
    cap.classList.remove('caption-animate');
    // force reflow to restart animation
    void cap.offsetWidth;
    cap.classList.add('caption-animate');
  }

  document.querySelectorAll('.gallery-item').forEach(function(track){
    let isDown = false, startX = 0, scrollLeft = 0, pointerId = null;
    const cards = () => Array.from(track.querySelectorAll('.gallery-card'));

    // animate caption initially for this gallery's parent
    const parent = track.closest('.rolling-gallery');
    if(parent) animateCaptionFor(parent);

    track.addEventListener('pointerdown', function(e){
      isDown = true;
      pointerId = e.pointerId;
      track.classList.add('gallery-dragging');
      startX = e.pageX - track.offsetLeft;
      scrollLeft = track.scrollLeft;
      track.setPointerCapture(pointerId);
    });
    track.addEventListener('pointermove', function(e){
      if(!isDown) return;
      e.preventDefault();
      const x = e.pageX - track.offsetLeft;
      const walk = (startX - x);
      track.scrollLeft = scrollLeft + walk;
    });
    const end = function(e){
      if(!isDown) return;
      isDown = false;
      track.classList.remove('gallery-dragging');
      try{ track.releasePointerCapture(pointerId); }catch(_){}
      // snap to nearest card center
      const cardList = cards();
      if(cardList.length === 0) return;
      const viewportCenter = track.scrollLeft + (track.clientWidth / 2);
      let nearestIndex = 0, minDiff = Infinity;
      cardList.forEach((c, idx)=>{
        const cCenter = c.offsetLeft + (c.offsetWidth/2);
        const diff = Math.abs(cCenter - viewportCenter);
        if(diff < minDiff){ minDiff = diff; nearestIndex = idx; }
      });
      const targetScroll = Math.max(0, Math.round((cardList[nearestIndex].offsetLeft + cardList[nearestIndex].offsetWidth/2) - track.clientWidth/2));
      smoothScrollTo(track, targetScroll, 420);

      // retrigger caption animation for visual feedback
      if(parent) {
        // small delay so entrance happens after snap
        setTimeout(()=> animateCaptionFor(parent), 420);
      }
    };
    track.addEventListener('pointerup', end);
    track.addEventListener('pointercancel', end);
    track.addEventListener('pointerleave', end);

    // wheel horizontal support (use native smooth scrollBy)
    track.addEventListener('wheel', function(e){
      if(Math.abs(e.deltaY) > Math.abs(e.deltaX)){
        e.preventDefault();
        const delta = Math.sign(e.deltaY) * Math.min(120, Math.abs(e.deltaY)) * 1.2;
        track.scrollBy({ left: delta, behavior: 'smooth' });
        // give small feedback to caption when user scrolls quickly
        if(parent) {
          clearTimeout(track._captionTimeout);
          track._captionTimeout = setTimeout(()=> animateCaptionFor(parent), 300);
        }
      }
    }, {passive: false});

    // prev/next buttons unchanged but use smoothScrollTo and animate caption
    if(parent){
      const prev = parent.querySelector('.gallery-prev');
      const next = parent.querySelector('.gallery-next');
      if(prev) prev.addEventListener('click', function(){
        const cardList = cards();
        if(!cardList.length) return;
        const viewportCenter = track.scrollLeft + (track.clientWidth / 2);
        let currentIndex = 0, minDiff = Infinity;
        cardList.forEach((c, idx)=>{
          const cCenter = c.offsetLeft + (c.offsetWidth/2);
          const diff = Math.abs(cCenter - viewportCenter);
          if(diff < minDiff){ minDiff = diff; currentIndex = idx; }
        });
        const targetIndex = Math.max(0, currentIndex - 1);
        const targetScroll = Math.max(0, Math.round((cardList[targetIndex].offsetLeft + cardList[targetIndex].offsetWidth/2) - track.clientWidth/2));
        smoothScrollTo(track, targetScroll, 420);
        setTimeout(()=> animateCaptionFor(parent), 420);
      });
      if(next) next.addEventListener('click', function(){
        const cardList = cards();
        if(!cardList.length) return;
        const viewportCenter = track.scrollLeft + (track.clientWidth / 2);
        let currentIndex = 0, minDiff = Infinity;
        cardList.forEach((c, idx)=>{
          const cCenter = c.offsetLeft + (c.offsetWidth/2);
          const diff = Math.abs(cCenter - viewportCenter);
          if(diff < minDiff){ minDiff = diff; currentIndex = idx; }
        });
        const targetIndex = Math.min(cardList.length - 1, currentIndex + 1);
        const targetScroll = Math.max(0, Math.round((cardList[targetIndex].offsetLeft + cardList[targetIndex].offsetWidth/2) - track.clientWidth/2));
        smoothScrollTo(track, targetScroll, 420);
        setTimeout(()=> animateCaptionFor(parent), 420);
      });
    }
  });
});
